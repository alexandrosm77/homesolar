def resolve_theme(request: Request) -> str:
    param = request.query_params.get("theme")
    if param in SUPPORTED_THEMES:
        return param
    cookie = request.cookies.get(THEME_COOKIE_NAME)
    if cookie in SUPPORTED_THEMES:
        return cookie
    return DEFAULT_THEME


def resolve_language(request: Request, user_language: str | None = None) -> str:
    param = request.query_params.get("lang")
    if param in SUPPORTED_LANGUAGES:
        return param
    if user_language in SUPPORTED_LANGUAGES:
        return user_language
    cookie = request.cookies.get(LANGUAGE_COOKIE_NAME)
    if cookie in SUPPORTED_LANGUAGES:
        return cookie
    header = request.headers.get("accept-language", "")
    if "el" in header.lower():
        return "el"
    return DEFAULT_LANGUAGE


def get_translations(lang: str) -> dict[str, str]:
    return _TRANSLATIONS.get(lang, _TRANSLATIONS[DEFAULT_LANGUAGE])


def translate(lang: str, key: str, **kwargs: object) -> str:
    table = _TRANSLATIONS.get(lang, _TRANSLATIONS[DEFAULT_LANGUAGE])
    text = table.get(key) or _TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    return text.format(**kwargs) if kwargs else text
